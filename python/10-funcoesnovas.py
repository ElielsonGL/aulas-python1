import math

#inteiro pra cima
print(math.ceil(4.2))

#inteiro pra baixo
print(math.floor(3.9))

#mod = restante de uma divisão
print(math.fmod(9, 4))

#raiz quadrada
print(math.sqrt(36))

#funções padrões
lista = [10, 20, 30]
tam = len(lista) #len conta os elementos dentro da lista
print("A lista", lista, " tem tamanho", tam)

soma = sum(lista)
print("A lista", lista, " tem um somatório", soma)

